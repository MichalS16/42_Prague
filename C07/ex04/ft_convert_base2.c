int	ft_strlen(char *str)
{
	int	i;

	i = 0;
	while (str[i])
		i++;
	return (i);
}

int	member(char c, char *base)
{
	int	i;

	i = 0;
	while (base[i])
	{
		if (base[i] == c)
			return (1);
		i++;
	}
	return (0);
}

int	to_decimal(char c, char *base)
{
	int	i;

	i = 0;
	while (base[i])
	{
		if (base[i] == c)
			return (i);
		i++;
	}
	return (0);
}

static int	has_duplicate(char *base, int i)
{
	int	j;

	j = i + 1;
	while (base[j])
	{
		if (base[i] == base[j])
			return (1);
		j++;
	}
	return (0);
}

int	base_is_valid(char *base)
{
	int	i;

	i = 0;
	while (base[i])
	{
		if (base[i] == '+' || base[i] == '-' || base[i] <= 32)
			return (0);
		if (has_duplicate(base, i))
			return (0);
		i++;
	}
	if (i < 2)
		return (0);
	return (1);
}
