#include <unistd.h>

void	ft_putstr(char *s)
{
	int	i;

	i = 0;
	while (s[i])
		i++;
	write(1, s, i);
}

int	ft_starts_with(char *s, char *prefix)
{
	while (*prefix)
	{
		if (*s != *prefix)
			return (0);
		s++;
		prefix++;
	}
	return (1);
}

void	ft_putstr_fd(char *s, int fd)
{
	int	i;

	i = 0;
	while (s[i])
		i++;
	write(fd, s, i);
}
